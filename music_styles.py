"""סגנונות המוזיקה של הריילס (לפי הכלי המוביל), כדי שהבוט ילמד איזה סגנון מביא יותר חשיפה."""
STYLES = {
    "פסנתר": ["06", "07", "10", "16", "17", "18", "21", "23"],
    "נבל": ["02", "11", "15", "20", "25"],
    "גיטרה": ["08", "09", "12", "19", "24"],
    "מיתרים ונשיפה": ["01", "03", "04", "14"],
    "פעמונים ותיבת נגינה": ["05", "13", "22"],
}


def style_of(track_name):
    pre = (track_name or "")[:2]
    return next((s for s, ids in STYLES.items() if pre in ids), None)
